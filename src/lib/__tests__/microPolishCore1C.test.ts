function readAssetBuffer(relPath: string): ArrayBuffer {
  const fullPath = path.resolve(process.cwd(), relPath);
  const buf = fs.readFileSync(fullPath);
  return buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength);
}

function round2(n: number): number {
  const r = Math.round((n + Number.EPSILON) * 100) / 100;
  return Object.is(r, -0) ? 0 : r;
}

test('Final Core Micro-Polish (Q1–Q3): Art. 270 NK RF non-deductible profit tax base, Art. 218 NK RF YTD child deduction limit (56 082.00 ₽ Sep NDFL), КадровыйПеревод, fixed alimony label, and clean Номенклатура', async () => {
  const q1Input = { name: 'Хоз.csv', buffer: readAssetBuffer('public/assets/aistudio/____09f9d030.csv') };
  const q2Input = { name: 'Хоз(1).csv', buffer: readAssetBuffer('public/assets/aistudio/____1__443ffb42.csv') };
  const q3Input = { name: 'Хоз(2).csv', buffer: readAssetBuffer('public/assets/aistudio/____2__232e9040.csv') };

  const batch = await processBatchFiles([q1Input, q2Input, q3Input], null, {
    reportingYear: 2026,
  });

  const fixed = autoFixAllBy1CDb({
    db1C: null,
    operations: batch.operations,
    calculateCurrentOsv: (ops, dateToOverride) =>
      calculateOsvReport({
        db1C: null,
        operations: ops,
        dateFrom: '2026-01-01',
        dateTo: dateToOverride || '2026-09-30',
        reportingYear: 2026,
        includeQueuedOperations: true,
      }),
    periodEndDate: '2026-09-30',
    reportingYear: 2026,
  });

  const ops = fixed.operations;
  const userOps = ops.filter((o) => !o.autoGeneratedKind);

  // =========================================================================
  // 1. Art. 270 NK RF Non-Deductible Expenses & YTD Profit Tax Base (99.02.1)
  // =========================================================================
  const giftOp = userOps.find((o) => o.date === '2026-08-17' && /подар/iu.test(o.description));
  assert.ok(giftOp, '17.08.2026 gratuitous employee gifts operation must exist');
  const giftCostEntry = giftOp.entries.find((e) => e.debit === '91.02' && e.credit === '73.03');
  const giftVatEntry = giftOp.entries.find((e) => e.debit === '91.02' && e.credit === '68.02');
  assert.ok(giftCostEntry, 'Gift cost posting Дт 91.02 Кт 73.03 must exist');
  assert.ok(giftVatEntry, 'Gift VAT posting Дт 91.02 Кт 68.02 must exist');
  assert.equal(giftCostEntry.amount, 120000);
  assert.equal(giftVatEntry.amount, 24000);
  assert.equal(giftCostEntry.nonDeductibleForProfitTax, true, 'Gift cost must be flagged nonDeductibleForProfitTax: true (п. 16 ст. 270 НК РФ)');
  assert.equal(giftVatEntry.nonDeductibleForProfitTax, true, 'Gift VAT must be flagged nonDeductibleForProfitTax: true (п. 16 ст. 270 НК РФ)');

  const matAidOp = userOps.find((o) => o.date === '2026-09-20' && /материальн\S*\s+помощ/iu.test(o.description));
  assert.ok(matAidOp, '20.09.2026 material aid operation must exist');
  const matAidPrincipalEntry = matAidOp.entries.find(
    (e) => e.debit === '91.02' && (e.credit === '73.03' || e.credit === '70')
  );
  const matAidIns6909 = matAidOp.entries.find((e) => e.debit === '91.02' && e.credit === '69.09');
  const matAidIns6911 = matAidOp.entries.find((e) => e.debit === '91.02' && e.credit === '69.11');
  assert.ok(matAidPrincipalEntry, 'Material aid principal posting Дт 91.02 Кт 73.03 must exist');
  assert.equal(matAidPrincipalEntry.amount, 44000);
  assert.equal(
    matAidPrincipalEntry.nonDeductibleForProfitTax,
    true,
    'Material aid principal must be flagged nonDeductibleForProfitTax: true (п. 23 ст. 270 НК РФ)'
  );
  assert.ok(matAidIns6909 && matAidIns6909.amount === 12000, 'Material aid insurance 69.09 = 12 000 ₽ must exist');
  assert.ok(matAidIns6911 && matAidIns6911.amount === 80, 'Material aid insurance 69.11 = 80 ₽ must exist');
  assert.notEqual(
    matAidIns6909.nonDeductibleForProfitTax,
    true,
    'Insurance contributions 69.09 on material aid remain deductible for profit tax!'
  );
  assert.notEqual(
    matAidIns6911.nonDeductibleForProfitTax,
    true,
    'Insurance contributions 69.11 on material aid remain deductible for profit tax!'
  );

  // Verify Q1 and Q2 remain untouched (0 non-deductible expenses in Q1–Q2)
  const osvQ1 = calculateOsvReport({
    db1C: null,
    operations: ops,
    dateFrom: '2026-01-01',
    dateTo: '2026-03-31',
    reportingYear: 2026,
    includeQueuedOperations: true,
  });
  const osvH1 = calculateOsvReport({
    db1C: null,
    operations: ops,
    dateFrom: '2026-01-01',
    dateTo: '2026-06-30',
    reportingYear: 2026,
    includeQueuedOperations: true,
  });
  assert.equal(
    osvQ1.leafRows.find((r) => r.code === '99.02.1')?.endDebit ?? 0,
    round2((osvQ1.leafRows.find((r) => r.code === '99.01.1')?.endCredit ?? 0) * 0.2),
    'Q1 profit tax remains exact 20% of Q1 BU profit (zero gifts/aid in Q1)'
  );
  assert.equal(
    osvH1.leafRows.find((r) => r.code === '99.02.1')?.endDebit ?? 0,
    round2((osvH1.leafRows.find((r) => r.code === '99.01.1')?.endCredit ?? 0) * 0.2),
    'H1 profit tax remains exact 20% of H1 BU profit (zero gifts/aid in H1)'
  );

  // Verify Q3 / 9M profit tax includes 188 000 ₽ non-deductible expenses and mentions ст. 270 НК РФ in description
  const osv9M = calculateOsvReport({
    db1C: null,
    operations: ops,
    dateFrom: '2026-01-01',
    dateTo: '2026-09-30',
    reportingYear: 2026,
    includeQueuedOperations: true,
  });
  const buProfit9M = round2(
    (osv9M.leafRows.find((r) => r.code === '99.01.1')?.endCredit ?? 0) -
      (osv9M.leafRows.find((r) => r.code === '99.01.1')?.endDebit ?? 0)
  );
  const expectedTaxBase9M = Math.max(0, round2(buProfit9M + 188000));
  const expectedProfitTax9M = round2(expectedTaxBase9M * 0.2);
  assert.equal(
    osv9M.leafRows.find((r) => r.code === '99.02.1')?.endDebit ?? 0,
    expectedProfitTax9M,
    '9M 99.02.1 ending debit must equal 20% * (buProfitYTD + 188 000)'
  );

  const sepClosingOp = userOps.find((o) => o.date === '2026-09-30' && o.category === 'closing');
  assert.ok(sepClosingOp, '30.09.2026 closing operation must exist');
  const sepTaxEntry = sepClosingOp.entries.find((e) => e.debit === '99.02.1' && e.credit === '68.04.1');
  assert.ok(sepTaxEntry, '30.09.2026 closing must contain Дт 99.02.1 Кт 68.04.1 profit tax entry');
  assert.match(
    sepTaxEntry.description,
    /ст\.\s*270\s*НК\s*РФ/iu,
    `99.02.1 posting description must explain permanent differences under ст. 270 НК РФ, got: ${sepTaxEntry.description}`
  );
  assert.match(
    sepTaxEntry.description,
    /188\s*000,00/u,
    `99.02.1 posting description must include 188 000,00 ₽ non-deductible YTD breakdown, got: ${sepTaxEntry.description}`
  );
  assert.equal(
    ops.some((o) => o.docNumber === 'РЕГЛ-ЗАКР'),
    false,
    'autoFixAllBy1CDb must agree with postingEngine YTD taxBase and never create phantom РЕГЛ-ЗАКР'
  );

  // =========================================================================
  // 2. Art. 218 NK RF YTD Income Limit (450 000 ₽) & Exact September NDFL
  // =========================================================================
  // Check Virtual1CState right BEFORE September payroll_accrual and AFTER September payroll_accrual:
  const sepPayrollIdx = ops.findIndex((o) => o.date === '2026-09-30' && o.category === 'payroll_accrual');
  assert.ok(sepPayrollIdx >= 0, '30.09.2026 payroll_accrual must exist');
  const sepPayrollOp = ops[sepPayrollIdx];

  const { finalState: stateAfterSepPayroll } = buildVirtual1CStateTimeline(
    null,
    ops.slice(0, sepPayrollIdx + 1)
  );
  assert.ok(stateAfterSepPayroll.payroll, 'virtual1CState.payroll must be populated');
  assert.equal(stateAfterSepPayroll.payroll.year, '2026');

  const barankinaEmp = stateAfterSepPayroll.employees.find((emp) =>
    /баранкин/iu.test(emp.fullName)
  );
  assert.ok(barankinaEmp, 'Баранкина Б.Б. must exist in stateAfterSepPayroll.employees');
  const barankinaKey = normalizePersonIdentityKey1C(barankinaEmp.fullName);
  assert.equal(
    stateAfterSepPayroll.payroll.ytdGiftTaxableByEmployee[barankinaKey],
    20000,
    'Баранкина Б.Б. YTD taxable gift (24 000 - 4 000) in virtual1CState.payroll = 20 000 ₽'
  );
  assert.equal(
    stateAfterSepPayroll.payroll.ytdMaterialAidTaxableByEmployee[barankinaKey],
    40000,
    'Баранкина Б.Б. YTD taxable material aid (44 000 - 4 000) in virtual1CState.payroll = 40 000 ₽'
  );
  assert.equal(
    stateAfterSepPayroll.payroll.ytdTaxableIncomeByEmployee[barankinaKey],
    471500,
    'Баранкина Б.Б. total YTD taxable income (411 500 + 20 000 + 40 000) in virtual1CState.payroll must equal 471 500 ₽ (> 450 000 ₽)'
  );
  assert.equal(barankinaEmp.ytdTaxableIncome, 471500);

  const sepNdflEntry = sepPayrollOp.entries.find((e) => e.debit === '70' && e.credit === '68.01');
  assert.ok(sepNdflEntry, 'September payroll must contain Дт 70 Кт 68.01 entry');
  assert.equal(
    sepNdflEntry.amount,
    56082,
    'September NDFL (Дт 70 Кт 68.01) must equal exact 56 082,00 ₽ (8 400 ₽ child deduction stops for Баранкина Б.Б. since 471 500 > 450 000)'
  );

  // =========================================================================
  // 3. Metadata Preparation for 1C Export
  // =========================================================================
  // 3a) Employee transfer on 01.06.2026 -> strictly docType1C = 'КадровыйПеревод'
  const transferOp = userOps.find(
    (o) => o.date === '2026-06-01' && /перевед/iu.test(o.description)
  );
  assert.ok(transferOp, '01.06.2026 HR transfer operation (Валеев В.В.) must exist');
  assert.equal(
    transferOp.docType1C,
    'КадровыйПеревод',
    'HR transfer must map strictly to docType1C = "КадровыйПеревод" (not "ПриемНаРаботу")'
  );

  // 3b) Fixed monthly alimony description -> 'фикс. 20 000,00 ₽' instead of '1/4 (25%)'
  const alimonyEntries = ops.flatMap((o) =>
    o.entries.filter((e) => e.debit === '70' && e.credit === '76.41')
  );
  const fixedAlimonyEntries = alimonyEntries.filter((e) => e.amount === 20000);
  assert.ok(
    fixedAlimonyEntries.length >= 4,
    `Expected at least 4 monthly fixed-amount (20 000 ₽) alimony withholding postings (June–September), got ${fixedAlimonyEntries.length}`
  );
  for (const alEntry of fixedAlimonyEntries) {
    assert.ok(
      alEntry.description.includes('фикс. 20 000,00 ₽'),
      `Fixed alimony entry description must contain "фикс. 20 000,00 ₽", got: "${alEntry.description}"`
    );
    assert.equal(
      alEntry.description.includes('1/4 (25%)'),
      false,
      `Fixed alimony entry description must NEVER contain "1/4 (25%)", got: "${alEntry.description}"`
    );
  }

  // 3c) Comma-concatenated strings excluded from Номенклатура directory (both Virtual1CState and Export Bundle)
  const { finalState: fullState } = buildVirtual1CStateTimeline(null, ops);
  const stateNomNames = fullState.nomenclature.map((n) => n.name);
  assert.equal(
    stateNomNames.some((n) => n.includes(',')),
    false,
    `virtual1CState.nomenclature must not contain comma-concatenated strings, got: ${JSON.stringify(stateNomNames)}`
  );
  assert.equal(
    stateNomNames.includes('Плита ПВХ, Заготовка МДФ, Клей'),
    false,
    'virtual1CState.nomenclature must exclude "Плита ПВХ, Заготовка МДФ, Клей"'
  );

  const bundle = buildExportBundle({
    mode: 'clean_db',
    db1C: null,
    operations: ops,
    osv: osv9M,
    reportingYear: 2026,
  });
  const xmlNomNames = Array.from(
    bundle.enterpriseDataXml.matchAll(
      /<Справочник\.Номенклатура>[\s\S]*?<Наименование>([^<]+)<\/Наименование>[\s\S]*?<\/Справочник\.Номенклатура>/gu
    )
  ).map((m) => m[1]);

  assert.equal(
    xmlNomNames.some((n) => n.includes(',')),
    false,
    `Exported <Справочник.Номенклатура> must NOT contain comma-concatenated strings, got: ${JSON.stringify(xmlNomNames)}`
  );
  assert.equal(
    xmlNomNames.includes('Плита ПВХ, Заготовка МДФ, Клей'),
    false,
    'Exported <Справочник.Номенклатура> must NOT contain "Плита ПВХ, Заготовка МДФ, Клей"'
  );
  assert.ok(xmlNomNames.includes('Плита ПВХ'), 'Individual item "Плита ПВХ" must be present in Номенклатура');
  assert.ok(xmlNomNames.includes('Заготовка МДФ'), 'Individual item "Заготовка МДФ" must be present in Номенклатура');
  assert.ok(xmlNomNames.includes('Клей'), 'Individual item "Клей" must be present in Номенклатура');

  assert.match(
    bundle.enterpriseDataXml,
    /<Документ\.КадровыйПеревод>/u,
    'EnterpriseData XML must emit <Документ.КадровыйПеревод> for HR transfer'
  );
  assert.match(
    bundle.bslCode,
    /Документы\.КадровыйПеревод/u,
    'BSL loader must emit Документы.КадровыйПеревод for HR transfer'
  );
});
