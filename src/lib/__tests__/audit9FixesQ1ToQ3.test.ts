function readAssetBuffer(relPath: string): ArrayBuffer {
  const fullPath = path.resolve(process.cwd(), relPath);
  const buf = fs.readFileSync(fullPath);
  return buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength);
}

test('End-to-end Q1–Q3 audit: all 9 accounting core, auto-fix, and EnterpriseData XML fixes', async () => {
  const q1Input = { name: 'Хоз.csv', buffer: readAssetBuffer('public/assets/aistudio/____09f9d030.csv') };
  const q2Input = { name: 'Хоз(1).csv', buffer: readAssetBuffer('public/assets/aistudio/____1__443ffb42.csv') };
  const q3Input = { name: 'Хоз(2).csv', buffer: readAssetBuffer('public/assets/aistudio/____2__232e9040.csv') };

  const batch = await processBatchFiles([q1Input, q2Input, q3Input], null, {
    reportingYear: 2026,
  });
  assert.equal(batch.operations.length, 207, 'Expected 207 operations across Q1 + Q2 + Q3');

  // Simulate autoFixAllBy1CDb EVEN when caller's calculateCurrentOsv had a stale Q2 endDate ('2026-06-30')
  // to guarantee generatePeriodClosingOperations NEVER reverses Q3 profit tax or invents phantom АВТ-СФА
  const fixedWithStaleFilter = autoFixAllBy1CDb({
    db1C: null,
    operations: batch.operations,
    calculateCurrentOsv: (ops) =>
      calculateOsvReport({
        db1C: null,
        operations: ops,
        dateFrom: '2026-01-01',
        dateTo: '2026-06-30',
        reportingYear: 2026,
        includeQueuedOperations: true,
      }),
    periodEndDate: '2026-09-30',
    reportingYear: 2026,
  });
  assert.equal(
    fixedWithStaleFilter.operations.some((o) => o.docNumber === 'РЕГЛ-ЗАКР'),
    false,
    'Must NOT generate phantom РЕГЛ-ЗАКР even if caller OSV filter was on an earlier quarter'
  );
  assert.equal(
    fixedWithStaleFilter.operations.some((o) => o.docNumber === 'АВТ-СФА'),
    false,
    'Must NOT generate phantom АВТ-СФА even if caller OSV filter was on an earlier quarter'
  );

  // Now run standard cumulative Q1–Q3 autoFixAllBy1CDb
  const fixed = autoFixAllBy1CDb({
    db1C: null,
    operations: batch.operations,
    calculateCurrentOsv: (ops, dateToOverride) =>
      calculateOsvReport({
        db1C: null,
        operations: ops,
        dateFrom: '2026-01-01',
        dateTo: dateToOverride || '2026-09-30',
        reportingYear: 2026,
        includeQueuedOperations: true,
      }),
    periodEndDate: '2026-09-30',
    reportingYear: 2026,
  });

  const ops = fixed.operations;
  const userOps = ops.filter((o) => !o.autoGeneratedKind);
  const q1Ops = userOps.slice(0, 57);
  const q2Ops = userOps.slice(57, 117);

  const finalOsv = calculateOsvReport({
    db1C: null,
    operations: ops,
    dateFrom: '2026-01-01',
    dateTo: '2026-09-30',
    reportingYear: 2026,
    includeQueuedOperations: true,
  });

  // --- FIX #1: Profit Tax YTD & ZERO phantom РЕГЛ-ЗАКР ---
  const reglZakrOps = ops.filter((o) => o.docNumber === 'РЕГЛ-ЗАКР');
  assert.equal(reglZakrOps.length, 0, 'No phantom РЕГЛ-ЗАКР should be generated when Q3 #89 already closed the quarter');
  const reverseTaxEntries = ops.flatMap((o) =>
    o.entries.filter((e) => e.debit.startsWith('68.04') && e.credit === '99.02.1')
  );
  assert.equal(reverseTaxEntries.length, 0, 'Q3 profit tax must never be reversed by 68.04.1 -> 99.02.1');
  const row9901 = finalOsv.leafRows.find((r) => r.code === '99.01.1');
  const row99021 = finalOsv.leafRows.find((r) => r.code === '99.02.1');
  const ytdProfit = Number(((row9901?.endCredit ?? 0) - (row9901?.endDebit ?? 0)).toFixed(2));
  const expectedYtdTax = Number((ytdProfit * 0.2).toFixed(2));
  assert.ok(ytdProfit > 15_000_000, `Expected substantial 9-month YTD profit on 99.01.1, got ${ytdProfit}`);
  assert.ok(
    Math.abs((row99021?.endDebit ?? 0) - expectedYtdTax) <= 0.02,
    `99.02.1 ending debit (${row99021?.endDebit}) must equal 20% of 99.01.1 YTD profit (${expectedYtdTax})`
  );

  // --- FIX #2 & #3: Default 20% VAT on OSNO sales/advances + 76.АВ deduction on refunds & offsets + ZERO phantom АВТ-СФА ---
  const avtSfaOps = ops.filter((o) => o.docNumber === 'АВТ-СФА');
  assert.equal(avtSfaOps.length, 0, 'No phantom АВТ-СФА should be generated on 30.09.2026');

  // Verify specific OSNO counterparties that omitted "с НДС" in row text
  const slavaAdv = userOps.find((o) => o.date === '2026-05-03' && o.counterpartyName.includes('Слава'));
  assert.equal(slavaAdv?.vatAmount, 386666.67, 'ООО «Слава» 03.05 advance 2 320 000 must accrue 76.АВ = 386 666.67');
  assert.equal(slavaAdv?.entries.some((e) => e.debit === '76.АВ' && e.credit === '68.02' && e.amount === 386666.67), true);

  const slavaSale = userOps.find((o) => o.date === '2026-07-28' && o.counterpartyName.includes('Слава'));
  assert.equal(slavaSale?.vatAmount, 386666.67, 'ООО «Слава» 28.07 handover 2 320 000 must charge 20/120 VAT = 386 666.67');
  assert.equal(slavaSale?.entries.some((e) => e.debit === '68.02' && e.credit === '76.АВ' && e.amount === 386666.67), true);

  const keramikaAdv = userOps.find((o) => o.date === '2026-06-02' && o.counterpartyName.includes('Керамика'));
  assert.equal(keramikaAdv?.vatAmount, 880000, 'ООО «Керамика» 02.06 advance 5 280 000 must accrue 76.АВ = 880 000');
  const keramikaSale = userOps.find((o) => o.date === '2026-06-18' && o.counterpartyName.includes('Керамика'));
  assert.equal(keramikaSale?.vatAmount, 880000, 'ООО «Керамика» 18.06 handover 5 280 000 must include VAT 880 000');

  const magnatAdv1 = userOps.find((o) => o.date === '2026-08-04' && o.counterpartyName.includes('Магнат'));
  assert.equal(magnatAdv1?.vatAmount, 253333.33, 'ООО «Магнат» 04.08 advance 1 520 000 must accrue 76.АВ = 253 333.33');
  const magnatRefund = userOps.find((o) => o.date === '2026-08-31' && o.counterpartyName.includes('Магнат'));
  assert.equal(
    magnatRefund?.entries.some((e) => e.debit === '68.02' && e.credit === '76.АВ' && e.amount === 253333.33),
    true,
    'ООО «Магнат» 31.08 advance refund 1 520 000 must restore Дт 68.02 Кт 76.АВ = 253 333.33 (п. 5 ст. 171 НК РФ)'
  );
  const magnatAdv2 = userOps.find((o) => o.date === '2026-09-01' && o.counterpartyName.includes('Магнат'));
  assert.equal(magnatAdv2?.vatAmount, 155000, 'ООО «Магнат» 01.09 advance 930 000 must accrue 76.АВ = 155 000');
  const magnatSale = userOps.find((o) => o.date === '2026-09-27' && o.counterpartyName.includes('Магнат'));
  assert.equal(magnatSale?.vatAmount, 155000, 'ООО «Магнат» 27.09 handover 930 000 must include VAT 155 000');

  const klyuchAdv = userOps.find((o) => o.date === '2026-08-05' && o.counterpartyName.includes('Ключ'));
  assert.equal(klyuchAdv?.vatAmount, 1782000, 'ООО «Ключ» 05.08 advance 10 692 000 must accrue 76.АВ = 1 782 000');
  const klyuchSale = userOps.find((o) => o.date === '2026-09-25' && o.counterpartyName.includes('Ключ'));
  assert.equal(klyuchSale?.vatAmount, 1782000, 'ООО «Ключ» 25.09 handover 10 692 000 must include VAT 1 782 000');

  const sonataSale = userOps.find((o) => o.date === '2026-08-31' && o.counterpartyName.includes('Соната'));
  assert.equal(sonataSale?.vatAmount, 80000, 'ООО «Соната» 31.08 handover 480 000 must include VAT 80 000');

  const zhilAdv = userOps.find((o) => o.date === '2026-09-06' && o.counterpartyName.includes('ЖилСтройИнвест'));
  assert.equal(zhilAdv?.vatAmount, 1446666.67, 'ООО «ЖилСтройИнвест» 06.09 advance 8 680 000 must accrue 76.АВ = 1 446 666.67');
  const zhilSale = userOps.find((o) => o.date === '2026-09-28' && o.counterpartyName.includes('ЖилСтройИнвест'));
  assert.equal(zhilSale?.vatAmount, 1280000, 'ООО «ЖилСтройИнвест» 28.09 handover 7 680 000 must include VAT 1 280 000');
  const zhilRefund = userOps.find(
    (o) => o.date === '2026-09-29' && o.counterpartyName.includes('ЖилСтройИнвест') && o.category === 'bank_out'
  );
  assert.equal(
    zhilRefund?.entries.some((e) => e.debit === '68.02' && e.credit === '76.АВ' && e.amount === 166666.67),
    true,
    'ООО «ЖилСтройИнвест» 29.09 partial advance refund 1 000 000 must restore 76.АВ = 166 666.67'
  );

  const row6202 = finalOsv.leafRows.find((r) => r.code === '62.02');
  const row76AV = finalOsv.leafRows.find((r) => r.code === '76.АВ');
  const expectedEnd76AV = Number((((row6202?.endCredit ?? 0) * 20) / 120).toFixed(2));
  assert.equal(row6202?.endCredit ?? 0, 0, 'Ending 62.02 on 30.09.2026 must equal 0.00 ₽');
  assert.equal(row76AV?.endDebit ?? 0, expectedEnd76AV, 'Ending 76.АВ on 30.09.2026 must equal round2(62.02 * 20/120) = 0.00 ₽');

  // --- FIX #4: June OS Depreciation of «Леса строительные» & July Disposal ---
  const juneClose = userOps.find((o) => o.date === '2026-06-30' && o.category === 'closing');
  assert.ok(juneClose, 'June closing (30.06.2026) must exist');
  assert.equal(
    juneClose.entries.some(
      (e) => e.credit === '02.01' && e.amount === 13333.33 && (e.creditSubconto || e.description || '').includes('Леса')
    ),
    true,
    'June closing (30.06.2026) must depreciate «Леса строительные» by 13 333.33 ₽ even though «Фрезерный станок» was sold 04.06'
  );
  const lesaDisposal = userOps.find(
    (o) => o.date === '2026-07-07' && o.category === 'os_disposal'
  );
  assert.ok(lesaDisposal, '07.07.2026 os_disposal of «Леса строительные» must exist');
  assert.equal(
    lesaDisposal.entries.some((e) => e.debit === '02.01' && e.credit === '01.09' && e.amount === 53333.32),
    true,
    'Disposal of «Леса строительные» on 07.07.2026 must write off 4 months of depreciation (53 333.32 ₽)'
  );
  assert.equal(
    lesaDisposal.entries.some((e) => e.debit === '91.02' && e.credit === '01.09' && e.amount === 746666.68),
    true,
    'Disposal of «Леса строительные» on 07.07.2026 must write off residual value 800 000 - 53 333.32 = 746 666.68 ₽'
  );

  // --- FIX #5: NDFL 13% on Employee Gifts Above 4 000 ₽ in August Payroll ---
  const augPayroll = userOps.find((o) => o.date === '2026-08-31' && o.category === 'payroll_accrual');
  assert.ok(augPayroll, 'August payroll_accrual must exist');
  const augNdflEntry = augPayroll.entries.find((e) => e.debit === '70' && e.credit === '68.01');
  assert.equal(
    augNdflEntry?.amount,
    66664,
    'August NDFL (Дт 70 Кт 68.01) must equal 53 664.00 (wages) + 13 000.00 (5 * 20 000 * 13% gifts) = 66 664.00 ₽'
  );

  // --- FIX #6: ООО «Косна» 08.08 Payment, ООО «Сбыт» 04.04 & 09.07, 91.02 vs 99.02.3 ---
  const kosnaOp = userOps.find((o) => o.date === '2026-08-08' && o.counterpartyName.includes('Косна'));
  assert.equal(
    kosnaOp?.entries.some((e) => e.debit === '60.01' && e.credit === '51' && e.amount === 316000),
    true,
    '08.08.2026 ООО «Косна» («Произведена оплата.») must generate Дт 60.01 Кт 51 = 316 000.00 ₽'
  );

  const sbytCourtOp = q2Ops[3];
  assert.equal(sbytCourtOp.date, '2026-04-04');
  assert.equal(
    sbytCourtOp.entries.some((e) => e.debit === '91.02' && e.credit === '76.02' && e.amount === 3000),
    true,
    '04.04.2026 court sanctions must post 3 000 ₽ to Дт 91.02 Кт 76.02'
  );
  assert.equal(
    sbytCourtOp.entries.some((e) => e.debit === '99.02.3' && e.credit === '76.02' && e.amount === 5000),
    true,
    '04.04.2026 tax sanctions must post 5 000 ₽ to Дт 99.02.3 Кт 76.02'
  );
  assert.equal(
    sbytCourtOp.entries.some((e) => e.debit === '60.01' && e.credit === '51' && e.amount === 195710),
    true,
    '04.04.2026 ООО «Сбыт» contract 177 payment must equal 120 000 + 56 000 + 5 590 + 14 120 = 195 710.00 ₽'
  );
  const sbytJulyPay = userOps.find(
    (o) => o.date === '2026-07-09' && o.counterpartyName.includes('Сбыт')
  );
  assert.ok(sbytJulyPay, '09.07.2026 ООО «Сбыт» payment must exist');
  assert.equal(sbytJulyPay.amount, 2128000, '09.07.2026 ООО «Сбыт» remaining debt payment must equal exact 2 128 000.00 ₽');

  // --- FIX #7: Exact Calendar Formula Сумма * Ставка% * Дней / 365 ---
  const mayBillInterest = userOps.find(
    (o) => o.date === '2026-05-31' && /вексел/iu.test(o.description)
  );
  assert.ok(mayBillInterest, '31.05.2026 promissory note interest must exist');
  assert.equal(
    mayBillInterest.amount,
    7898.63,
    '31.05.2026 promissory note interest for May (31 days) must equal 620 000 * 15% * 31 / 365 = 7 898.63 ₽'
  );

  // --- FIX #8: 20.01 Nomenclature Group Analytics & МЦ.02 Split Across Named Employees ---
  const cementDelivery = q1Ops[34];
  assert.equal(cementDelivery.date, '2026-03-09');
  const cement20Entry = cementDelivery.entries.find((e) => e.debit === '20.01');
  assert.ok(
    (cement20Entry?.debitSubconto || '').startsWith('Реконструкция кровли'),
    `09.03.2026 cement delivery must post to «Реконструкция кровли», got: ${cement20Entry?.debitSubconto}`
  );

  const workwearIssueAug = userOps.find(
    (o) => o.date === '2026-08-18' && o.category === 'workwear_issue'
  );
  assert.ok(workwearIssueAug, '18.08.2026 workwear_issue must exist');
  const ww20Entry = workwearIssueAug.entries.find((e) => e.debit === '20.01');
  assert.ok(
    (ww20Entry?.debitSubconto || '').startsWith('Благоустройство территории'),
    `18.08.2026 workwear issue must inherit «Благоустройство территории», got: ${ww20Entry?.debitSubconto}`
  );
  const mc02Entries = workwearIssueAug.entries.filter((e) => e.debit === 'МЦ.02');
  assert.equal(mc02Entries.length, 2, '18.08.2026 workwear issue to Баранкин and Петров must create 2 МЦ.02 entries');
  assert.equal(mc02Entries[0].amount, 22416.67);
  assert.equal(mc02Entries[1].amount, 22416.66);
  assert.equal(Number((mc02Entries[0].amount + mc02Entries[1].amount).toFixed(2)), 44833.33);

  // --- FIX #9: EnterpriseData_1C_Export.xml Organization & Nomenclature Hygiene + Double-Entry Balance ---
  assert.equal(finalOsv.totals.isEndBalanced, true, 'Final Q1–Q3 OSV must satisfy Σ Дт = Σ Кт to 0.00 kopeks');
  assert.equal(finalOsv.totals.endDiff, 0);

  const bundle = buildExportBundle({
    mode: 'clean_db',
    db1C: null,
    operations: ops,
    osv: finalOsv,
    reportingYear: 2026,
  });
  const xml = bundle.enterpriseDataXml;

  assert.match(xml, /<Справочник\.Организации>/u, 'XML must emit <Справочник.Организации>');
  assert.match(xml, /<Наименование>ООО &quot;Завод&quot;|<Наименование>ООО «Завод»/u, 'XML organization name must be ООО «Завод»');
  assert.match(xml, /<ИНН>7810119529<\/ИНН>/u, 'XML organization INN must be 7810119529');
  assert.match(xml, /<КПП>781001001<\/КПП>/u, 'XML organization KPP must be 781001001');
  assert.doesNotMatch(
    xml,
    /<Организация>\s*<Ссылка>[^<]*<\/Ссылка>\s*<Наименование><\/Наименование>/u,
    'Every document <Организация> block in XML must have non-empty <Наименование>'
  );

  const nomMatches = Array.from(
    xml.matchAll(/<Справочник\.Номенклатура>[\s\S]*?<Наименование>([^<]+)<\/Наименование>[\s\S]*?<\/Справочник\.Номенклатура>/gu)
  ).map((m) => m[1]);
  assert.ok(nomMatches.includes('Паркет'), 'XML <Справочник.Номенклатура> must contain clean item «Паркет» from Q3 #68');
  for (const bad of [
    'Вексель',
    'На основании счета',
    'Проценты по векселям',
    'Задолженность по процентам',
    'Долговые ценные бумаги',
  ]) {
    assert.equal(
      nomMatches.some((n) => n.toLowerCase().includes(bad.toLowerCase())),
      false,
      `XML <Справочник.Номенклатура> must NOT contain "${bad}", got: ${JSON.stringify(nomMatches)}`
    );
  }
  assert.equal(
    nomMatches.some((n) => /кредит\s+в\s+банк/iu.test(n)),
    false,
    `XML <Справочник.Номенклатура> must NOT contain bank loan descriptions, got: ${JSON.stringify(nomMatches)}`
  );
});
