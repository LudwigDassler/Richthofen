import type {
  BusinessOperation,
  ChatMessage,
  OpeningBalanceEntry,
  OrganizationCard,
  OsvDiscrepancy,
} from '@/types/accounting';

export interface ChatContextPayload {
  organization?: OrganizationCard;
  openingBalances?: OpeningBalanceEntry[];
  activeOperation?: BusinessOperation | null;
  operationsSummary?: unknown;
  osvSummary?: unknown;
  discrepancies?: OsvDiscrepancy[];
}

function fmtRub(amount: number | undefined | null): string {
  const num = typeof amount === 'number' && Number.isFinite(amount) ? amount : 0;
  return `${num.toLocaleString('ru-RU', {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  })} ₽`;
}

export function stringifyOperationsSummary(summary: unknown): string {
  if (!summary) return 'Список операций не передан.';
  if (typeof summary === 'string') return summary;
  if (Array.isArray(summary)) {
    return summary
      .slice(0, 20)
      .map((item) => {
        if (typeof item === 'string') return `- ${item}`;
        if (item && typeof item === 'object') {
          const rec = item as Record<string, unknown>;
          const num = rec.number ?? '?';
          const date = rec.date ?? '';
          const desc = rec.rawDescription ?? rec.description ?? '';
          const amt =
            typeof rec.resolvedAmount === 'number'
              ? fmtRub(rec.resolvedAmount)
              : typeof rec.amount === 'number'
                ? fmtRub(rec.amount)
                : '';
          const status = rec.status ? ` [${String(rec.status)}]` : '';
          return `- Оп. №${String(num)} (${String(date)}): ${String(desc)} — ${amt}${status}`;
        }
        return '';
      })
      .filter(Boolean)
      .join('\n');
  }
  try {
    return JSON.stringify(summary);
  } catch {
    return String(summary);
  }
}

export function stringifyOsvSummary(osvSummary: unknown): string {
  if (!osvSummary) return 'Сводка ОСВ не передана.';
  if (typeof osvSummary === 'string') return osvSummary;
  if (typeof osvSummary === 'object') {
    const rec = osvSummary as Record<string, unknown>;
    const lines: string[] = [];
    if (typeof rec.totalStartDebit === 'number' || typeof rec.totalEndDebit === 'number') {
      lines.push(
        `Итого Сальдо нач.: Дт ${fmtRub(rec.totalStartDebit as number)} / Кт ${fmtRub(rec.totalStartCredit as number)}`
      );
      lines.push(
        `Итого Обороты: Дт ${fmtRub(rec.totalTurnoverDebit as number)} / Кт ${fmtRub(rec.totalTurnoverCredit as number)}`
      );
      lines.push(
        `Итого Сальдо кон.: Дт ${fmtRub(rec.totalEndDebit as number)} / Кт ${fmtRub(rec.totalEndCredit as number)}`
      );
    }
    if (Array.isArray(rec.rows)) {
      const leafRows = rec.rows
        .filter((r): r is Record<string, unknown> => Boolean(r && typeof r === 'object' && !r.isGroup))
        .slice(0, 25);
      for (const r of leafRows) {
        lines.push(
          `Счет ${String(r.accountCode)}: нач Дт ${fmtRub(r.startDebit as number)} Кт ${fmtRub(r.startCredit as number)} | обор Дт ${fmtRub(r.turnoverDebit as number)} Кт ${fmtRub(r.turnoverCredit as number)} | кон Дт ${fmtRub(r.endDebit as number)} Кт ${fmtRub(r.endCredit as number)}${r.hasRedBalance ? ' [КРАСНОТА!]' : ''}`
        );
      }
    }
    if (lines.length > 0) return lines.join('\n');
    try {
      return JSON.stringify(osvSummary);
    } catch {
      return String(osvSummary);
    }
  }
  return String(osvSummary);
}

export function buildChatSystemPrompt(context?: ChatContextPayload): string {
  const org = context?.organization;
  const activeOp = context?.activeOperation;
  const balances = context?.openingBalances ?? [];
  const discrepancies = context?.discrepancies ?? [];

  const orgBlock = org
    ? `Организация: ${org.name} (ИНН ${org.inn}, КПП ${org.kpp}), система налогообложения: ${org.taxSystem}, базовая ставка НДС: ${org.defaultVatRate}%, списание счета 26: ${org.costingMethod === 'direct-costing' ? 'Директ-костинг (на 90.08.1)' : 'В себестоимость (на 20.01)'}, период: ${org.periodLabel}.`
    : 'Организация на ОСНО, НДС 20%.';

  const balancesBlock =
    balances.length > 0
      ? balances
          .map(
            (b) =>
              `- Счет ${b.accountCode}${b.subconto1 ? ` (${b.subconto1}${b.subconto2 ? `, ${b.subconto2}` : ''})` : ''}: Дт ${fmtRub(b.debit)} / Кт ${fmtRub(b.credit)}`
          )
          .join('\n')
      : 'Нет данных о начальных остатках.';

  const activeOpBlock = activeOp
    ? [
        `Операция №${activeOp.number} от ${activeOp.date}: ${activeOp.rawDescription}`,
        `Статус: ${activeOp.status}, Итоговая сумма: ${fmtRub(activeOp.resolvedAmount)} (явная в условии: ${activeOp.explicitAmount !== null ? fmtRub(activeOp.explicitAmount) : 'не указана — берется из начальных остатков'})`,
        `Маршрут в 1С 8.3: ${activeOp.menuPath1C.join(' → ')}`,
        `Документ 1С: ${activeOp.documentType1C} (Вид операции: ${activeOp.operationKind1C})`,
        `УПД / СФ: ${activeOp.hasUpdOrSf ? activeOp.updLabel || 'Да' : 'Нет'}`,
        `Проводки:\n${activeOp.postings
          .map(
            (p) =>
              `  * Дт ${p.debitAccount} (${p.debitSubconto.join(', ') || '—'}) — Кт ${p.creditAccount} (${p.creditSubconto.join(', ') || '—'}): ${fmtRub(p.amount)} (${p.comment})`
          )
          .join('\n')}`,
      ].join('\n')
    : 'Активная операция не выбрана.';

  const discrepanciesBlock =
    discrepancies.length > 0
      ? discrepancies
          .map(
            (d) =>
              `- [${d.severity.toUpperCase()}] Счета ${d.accountsAffected.join(', ')} (разница ${fmtRub(d.diffAmount)}): ${d.title}. Причина: ${d.probableCause}. Как исправить в 1С: ${d.howToFixIn1C}`
          )
          .join('\n')
      : 'Расхождений в сверке ОСВ сейчас не зафиксировано.';

  return `Ты — «Личный бухгалтер», дружелюбный, точный и опытный наставник по 1С:Бухгалтерия 8.3 (редакция 3.0, интерфейс «Такси») и российскому бухучету (РСБУ).
Ты помогаешь студенту или начинающему бухгалтеру выполнить его КОНКРЕТНУЮ задачу в 1С 8.3 и свести Оборотно-сальдовую ведомость (ОСВ) до копейки.

ПРАВИЛА ОТВЕТА:
1. Отвечай на русском языке, четко структурированно (используй жирный шрифт **...**, списки и коды счетов в обратных кавычках, например \`60.02\`, \`20.01\`, \`19.03\`).
2. ОБЯЗАТЕЛЬНО опирайся на реальные цифры, названия контрагентов, договоров и суммы в рублях из контекста задачи ниже! Не давай абстрактных ответов, когда перед тобой конкретная операция студента.
3. Указывай точные пути в меню 1С:Бухгалтерия 8.3 (ред. 3.0, интерфейс «Такси»), названия кнопок, закладок и тумблеров (например, тумблер «УПД» под табличной частью).

=== КОНТЕКСТ ТЕКУЩЕЙ ЗАДАЧИ СТУДЕНТА ===
${orgBlock}

НАЧАЛЬНЫЕ ОСТАТКИ:
${balancesBlock}

ТЕКУЩАЯ ОТКРЫТАЯ ОПЕРАЦИЯ В НАВИГАТОРЕ:
${activeOpBlock}

СВОДКА ОПЕРАЦИЙ ЗАДАЧИ:
${stringifyOperationsSummary(context?.operationsSummary)}

ТЕКУЩАЯ ОСВ:
${stringifyOsvSummary(context?.osvSummary)}

ДИАГНОСТИКА СВЕРКИ ОСВ ПОЛЬЗОВАТЕЛЯ:
${discrepanciesBlock}`;
}

export function generateLocalExpertReply(
  messages: ChatMessage[],
  context?: ChatContextPayload
): string {
  const lastUserMsg = [...messages].reverse().find((m) => m.role === 'user');
  const question = (lastUserMsg?.content || '').trim();
  const q = question.toLowerCase();

  const org = context?.organization;
  const activeOp = context?.activeOperation ?? null;
  const balances = context?.openingBalances ?? [];
  const discrepancies = context?.discrepancies ?? [];
  const vatRate = org?.defaultVatRate ?? 20;

  const opHeader = activeOp
    ? `По вашей открытой **Операции №${activeOp.number} от ${activeOp.date}** (*«${activeOp.rawDescription}»*, сумма **${fmtRub(activeOp.resolvedAmount)}**):`
    : '';

  // ---------------------------------------------------------------------------
  // 1. Вопрос о расхождениях в ОСВ («Почему у меня расхождение в ОСВ?»)
  // ---------------------------------------------------------------------------
  if (/(?:расхожден|не\s+сходитс|ошибк.*в\s+осв|сверк.*осв|почему.*в\s+осв|оборотно-сальдов)/i.test(q)) {
    if (discrepancies.length > 0) {
      const items = discrepancies
        .map(
          (d, idx) =>
            `${idx + 1}. **${d.title}** (счета ${d.accountsAffected.map((a) => `\`${a}\``).join(', ')}, дельта **${fmtRub(d.diffAmount)}**)\n` +
            `   - **Причина:** ${d.probableCause}\n` +
            `   - **Как исправить в 1С 8.3:** ${d.howToFixIn1C}`
        )
        .join('\n\n');

      return (
        `Я проанализировал вашу сверку ОСВ — сейчас обнаружено **${discrepancies.length} расхождений**:\n\n` +
        `${items}\n\n` +
        `**Совет:** после исправления документа в 1С обязательно выполните **Операции → Закрытие месяца → Перепровести документы за месяц**, чтобы восстановилась хронология зачета авансов и списания себестоимости.`
      );
    }

    return (
      `Сейчас в таблице **«Сверить мою ОСВ из 1С»** расхождений не зафиксировано (либо вы еще не ввели свои цифры из 1С).\n\n` +
      `Перейдите во вкладку **Оборотно-сальдовая ведомость (ОСВ) → Сверить мою ОСВ из 1С** и вставьте ваши остатки (или нажмите кнопку *«Смоделировать типичную ошибку»*).\n\n` +
      `Вот **4 главные причины**, из-за которых в этой задаче чаще всего не сходится ОСВ в 1С 8.3:\n` +
      `- **Завис аванс на счетах \`60.01\` и \`60.02\`** — в платежке поставщику и в документе *Поступление* выбраны разные договоры, либо время проведения списания с р/сч позже поступления.\n` +
      `- **Остался дебетовый остаток на \`19.03\` или \`19.04\`** — под табличной частью документа поступления не включен зеленый тумблер **«УПД»** (или не стоит галочка *«Отразить вычет НДС в книге покупок датой получения»*).\n` +
      `- **Задвоился оборот по кассе \`50.01\` и банку \`51\`** — при снятии наличных в кассу провели и ПКО, и *Списание с расчетного счета* (в 1С 8.3 проводку делает **только ПКО**!).\n` +
      `- **Не закрылся счет \`20.01\` в конце месяца** — Номенклатурная группа в расходах (\`20.01\`) не совпала буква в букву с Номенклатурной группой в документе *Реализация (Услуги)* по счету \`90.01.1\`.`
    );
  }

  // ---------------------------------------------------------------------------
  // 2. Вопрос «Почему здесь счет 20.01, а не 41?» (выбор между 20.01, 41.01, 10.01, 26)
  // ---------------------------------------------------------------------------
  if (
    /(?:почему.*20|20\.01.*41|41.*20\.01|разниц.*между\s+10.*41|счет\s+41\s+или\s+20|счет\s+10\s+или\s+41)/i.test(q)
  ) {
    const uses41 = activeOp?.postings.some((p) => p.debitAccount === '41.01' || p.creditAccount === '41.01');
    const uses20 = activeOp?.postings.some((p) => p.debitAccount === '20.01' || p.creditAccount === '20.01');

    let specificContext = '';
    if (activeOp && uses41) {
      specificContext =
        `${opHeader}\n` +
        `В **этой** операции используется именно счет \`41.01\` (*«Товары на складах»*), так как ТМЦ приобретены **«для дальнейшей продажи»** без переработки! Если бы мы использовали их на строительном объекте, тогда применялись бы счета \`10.01\` → \`20.01\`.\n\n`;
    } else if (activeOp && uses20) {
      const sub20 = activeOp.postings.find((p) => p.debitAccount === '20.01')?.debitSubconto.join(' / ') || 'Объект СМР';
      specificContext =
        `${opHeader}\n` +
        `Здесь выбран счет \`20.01\` (*«Основное производство»*, субконто: **${sub20}**), а **не** \`41.01\`, потому что эти затраты формируют **себестоимость наших строительно-монтажных работ по конкретному объекту**, а не закупаются для перепродажи как готовый товар!\n\n`;
    } else if (activeOp) {
      const accs = Array.from(
        new Set(activeOp.postings.flatMap((p) => [p.debitAccount, p.creditAccount]))
      )
        .map((a) => `\`${a}\``)
        .join(', ');
      specificContext = `${opHeader} в ней задействованы счета ${accs}.\n\n`;
    }

    return (
      specificContext +
      `### Как безошибочно различать счета \`41.01\`, \`10.01\`, \`20.01\` и \`26\` в 1С 8.3:\n` +
      `- **Счет \`41.01\` «Товары на складах»** — ставится ТОЛЬКО тогда, когда мы покупаем ценности **для перепродажи** в неизменном виде (маркер в задаче: *«для дальнейшей продажи»*, оптовая торговля). Входящий НДС идет на \`19.03\`.\n` +
      `- **Счет \`10.01\` «Сырье и материалы»** — когда покупаем кирпич, цемент, топливо, запчасти на склад для использования в собственном производстве или строительстве. При поступлении это \`Дт 10.01 Кт 60.01\`, а при передаче на объект оформляется *Расход материалов* (\`Дт 20.01 Кт 10.01\`).\n` +
      `- **Счет \`20.01\` «Основное производство»** — собирает все **прямые затраты** по конкретному объекту / Номенклатурной группе: списанные материалы (\`Кт 10.01\`), работы субподрядчиков (\`Кт 60.01\`, НДС на \`19.04\`!), зарплату рабочих/прораба (\`Кт 70\`, \`69\`) и амортизацию производственных ОС (\`Кт 02.01\`).\n` +
      `- **Счет \`26\` «Общехозяйственные расходы»** — управленческие затраты, не привязанные к одному объекту (зарплата директора и главбуха, аренда офиса, интернет).`
    );
  }

  // ---------------------------------------------------------------------------
  // 3. Вопрос «Не закрывается 20 счет при закрытии месяца, что проверить?»
  // ---------------------------------------------------------------------------
  if (/(?:не\s+закрываетс.*20|закрыти.*20|закрыти.*месяц|счет\s+20\s+завис|не\s+закрылс.*26)/i.test(q)) {
    const costingNote =
      org?.costingMethod === 'full-absorption'
        ? 'распределение на счет `20.01` (метод полной себестоимости)'
        : '**Директ-костинг** — прямое списание в `Дт 90.08.1 Кт 26`';

    return (
      `Если в 1С:Бухгалтерия 8.3 (ред. 3.0) при выполнении **Операции → Закрытие месяца** счет \`20.01\` остается с дебетовым остатком, сначала проверьте, **была ли сдача работ заказчику в этом месяце**:\n\n` +
      `0. **Законное незавершенное производство (НЗП)!**\n` +
      `   - Если работы по объекту (например, *«Ремонт кровли с установкой кирпичной трубы»* по субподряду ООО «Управление») приняты на \`20.01\`, но **акт реализации заказчику (\`Кт 90.01.1\`) в апреле еще не выставлялся**, то остаток по дебету \`20.01\` (например, **1 960 000,00 ₽** без НДС) — это **НЕ ошибка, а экономически верное незавершенное производство (НЗП)**! При настройке учетной политики *«С учетом выручки»* счет \`20.01\` закроется в том месяце, когда объект сдадут заказчику.\n\n` +
      `Если же реализация работ заказчику **была**, но \`20.01\` все равно не закрылся — проверьте **5 технических точек в 1С 8.3**:\n` +
      `1. **100% совпадение «Номенклатурной группы» (причина у 90% студентов!):**\n` +
      `   - В документах затрат на \`20.01\` (*Расход материалов*, *Поступление услуг субподряда*, *Начисление зарплаты*) и в документе выручки **Продажи → Реализация → Услуги** (\`Кт 90.01.1\`) должна стоять **ТОЧНО ТА ЖЕ Номенклатурная группа**!\n` +
      `2. **Не перепутайте справочники «Номенклатура» и «Номенклатурные группы»:** счет \`20.01\` закрывается именно в разрезе *Номенклатурных групп*.\n` +
      `3. **Заполнено ли «Подразделение»:** в шапке/табличной части документов затрат на \`20.01\` должно быть указано подразделение.\n` +
      `4. **Учетная политика (\`Главное → Учетная политика\`):** настройка списания затрат со счета \`20\` (*Без учета выручки* спишет \`20.01\` даже без реализации; *С учетом выручки* оставит НЗП).\n` +
      `5. **Для счета \`26\`:** в вашей организации выбран метод ${costingNote} — счет \`26\` закрывается ежемесячно в \`Дт 90.08.1 Кт 26\` независимо от НЗП на \`20.01\`!`
    );
  }

  // ---------------------------------------------------------------------------
  // 4. Вопрос «Как правильно оформить УПД в 1С 8.3?» / Завис НДС на 19 счете
  // ---------------------------------------------------------------------------
  if (/(?:оформить\s+упд|тумблер\s+упд|упд\s+в\s+1с|счет-фактур|завис.*19|вычет\s+ндс|19\.03|19\.04)/i.test(q)) {
    const activeUpdNote = activeOp
      ? activeOp.hasUpdOrSf
        ? `\n\nВ вашей текущей **Операции №${activeOp.number}** УПД **применяется** (${activeOp.updLabel || 'тумблер УПД ВКЛ'}): это сразу формирует вычет НДС на сумму **${fmtRub(activeOp.vatBreakdown?.vatAmount ?? 0)}** в дебет счета \`68.02\`.`
        : `\n\nОбратите внимание: в текущей открытой **Операции №${activeOp.number}** (*${activeOp.documentType1C}*) УПД / счет-фактура **не требуется**.`
      : '';

    return (
      `### Как правильно провести УПД в 1С:Бухгалтерия 8.3 (ред. 3.0, интерфейс «Такси»):\n\n` +
      `1. **При покупке (\`Покупки → Поступление (акты, накладные, УПД)\`):**\n` +
      `   - В самом низу документа (слева под табличной частью) переключите тумблер **«УПД»** в положение **ВКЛ** (он подсветится зеленым).\n` +
      `   - Поля *«Накладная / Акт №»* и *«Счет-фактура №»* объединятся: введите единый номер и дату УПД поставщика (при **Статусе УПД = 1** он заменяет и первичный документ, и счет-фактуру).\n` +
      `   - Перейдите по ссылке созданного счета-фактуры и убедитесь, что стоит галочка **«Отразить вычет НДС в книге покупок датой получения»** — именно она автоматически делает вторую проводку:\n` +
      `     - \`Дт 68.02 Кт 19.03\` — по товарам (\`41.01\`) и материалам (\`10.01\`);\n` +
      `     - \`Дт 68.02 Кт 19.04\` — по услугам и субподрядным работам (\`20.01\`, \`26\`).\n` +
      `2. **При продаже (\`Продажи → Реализация (акты, накладные, УПД)\`):**\n` +
      `   - Аналогично включите внизу тумблер **«УПД»** (либо нажмите кнопку *«Выписать счет-фактуру»*). Программа начислит НДС проводкой \`Дт 90.03 Кт 68.02\` и зарегистрирует запись в Книге продаж.` +
      activeUpdNote
    );
  }

  // ---------------------------------------------------------------------------
  // 5. Разбор проводок и НДС по текущей операции
  // ---------------------------------------------------------------------------
  if (/(?:разбери\s+проводк|проводк.*и\s+ндс|текущ.*операц|объясни.*операц|как\s+посчита.*ндс|какие\s+проводк)/i.test(q)) {
    if (!activeOp) {
      return `Выберите любую операцию в левой панели **«Журнал операций»**, и я подробно разберу по ней маршрут в 1С 8.3, формулу НДС и каждую проводку \`Дт / Кт\`!`;
    }

    const vatLines = activeOp.vatBreakdown
      ? `\n\n**Расчет суммы и НДС (ставка ${activeOp.vatBreakdown.vatRate}%):**\n` +
        activeOp.vatBreakdown.steps.map((s) => `- ${s}`).join('\n')
      : `\n\n**НДС:** операция отражается без выделения НДС (итого **${fmtRub(activeOp.resolvedAmount)}**).`;

    const smartLinkLine = activeOp.smartLink
      ? `\n- **Умная привязка к остаткам:** сумма взята по правилу — *${activeOp.smartLink.description}* (счет \`${activeOp.smartLink.accountCode}\`).`
      : '';

    const postingsLines =
      activeOp.postings.length > 0
        ? activeOp.postings
            .map(
              (p, idx) =>
                `${idx + 1}. \`Дт ${p.debitAccount}\` (${p.debitSubconto.join(', ') || '—'}) → \`Кт ${p.creditAccount}\` (${p.creditSubconto.join(', ') || '—'}) — **${fmtRub(p.amount)}**\n   *Пояснение:* ${p.comment}`
            )
            .join('\n')
        : `- **Кадровый документ без бухгалтерских проводок Дт/Кт в дату оформления!** Документ *${activeOp.documentType1C}* записывает плановый оклад (**${fmtRub(activeOp.resolvedAmount)}**) в кадровые регистры, а проводки по начислению зарплаты (\`Дт 26 / 20.01 Кт 70\`), НДФЛ (\`Дт 70 Кт 68.01\`) и взносов (\`Кт 69.09 / 69.11\`) формируются в конце месяца регламентным документом **Начисление зарплаты**.`;

    const pitfallLines =
      activeOp.pitfalls.length > 0
        ? `\n\n**Что обязательно проверить в 1С 8.3:**\n` +
          activeOp.pitfalls.map((w) => `- **${w.title}** ${w.description}`).join('\n')
        : '';

    return (
      `### Полный разбор Операции №${activeOp.number} от ${activeOp.date}\n` +
      `**Содержание:** ${activeOp.rawDescription}\n` +
      `- **Путь в 1С 8.3 (Такси):** ${activeOp.menuPath1C.join(' → ')}\n` +
      `- **Документ:** *${activeOp.documentType1C}* (Вид операции: *${activeOp.operationKind1C}*)\n` +
      `- **Сумма операции:** **${fmtRub(activeOp.resolvedAmount)}**` +
      smartLinkLine +
      vatLines +
      `\n\n**Бухгалтерские проводки:**\n${postingsLines}` +
      pitfallLines
    );
  }

  // ---------------------------------------------------------------------------
  // 6. Зачет авансов (60.01 / 60.02 или 62.01 / 62.02)
  // ---------------------------------------------------------------------------
  if (/(?:аванс|предоплат|60\.02|62\.02|зачет\s+аванс)/i.test(q)) {
    return (
      `### Как работает автоматический зачет авансов (\`60.01 / 60.02\` и \`62.01 / 62.02\`) в 1С 8.3:\n\n` +
      `1. **Шаг 1 — Предоплата поставщику:** документ *Списание с расчетного счета* формирует \`Дт 60.02 Кт 51\` на полную сумму платежа с НДС.\n` +
      `2. **Шаг 2 — Поступление товаров / услуг:** при проведении документа *Поступление (акты, накладные, УПД)* программа видит дебетовое сальдо на \`60.02\` и **первым движением** делает зачет аванса:\n` +
      `   - \`Дт 60.01 Кт 60.02\` — зачтен ранее выданный аванс;\n` +
      `   - \`Дт 41.01 (10.01 / 20.01) Кт 60.01\` — оприходована стоимость без НДС;\n` +
      `   - \`Дт 19.03 (19.04) Кт 60.01\` — выделен НДС.\n\n` +
      `**Почему в 1С аванс иногда НЕ зачитывается (висит и Дт \`60.02\`, и Кт \`60.01\`):**\n` +
      `- В банковской выписке и в накладной выбраны **два разных договора** (например, в одном *«Основной договор»*, а в другом *«Договор №12-ПК»*);\n` +
      `- Поле *«Погашение задолженности»* переключено в режим *«Не погашать»* вместо **«Автоматически»**;\n` +
      `- Оба документа от одной даты, но время *Поступления* (например, 09:00:00) раньше времени *Списания с р/сч* (12:00:00). Перенесите время оплаты на более раннее и перепроведите оба документа!`
    );
  }

  // ---------------------------------------------------------------------------
  // 7. Касса 50.01, краснота по кассе, снятие наличных
  // ---------------------------------------------------------------------------
  if (/(?:касс|50\.01|пко|рко|краснот|наличн)/i.test(q)) {
    const cashOpening = balances
      .filter((b) => b.accountCode === '50.01' || b.accountCode === '50')
      .reduce((acc, b) => acc + b.debit - b.credit, 0);

    return (
      `### Правила работы с кассой (\`50.01\`) в 1С:Бухгалтерия 8.3:\n\n` +
      `1. **Снятие наличных с р/сч в кассу (\`Дт 50.01 Кт 51\`):**\n` +
      `   - Оформляется **ТОЛЬКО** документом **Банк и касса → Кассовые документы → Поступление (ПКО)** с видом операции *«Получение наличных в банке»*!\n` +
      `   - Документ *Списание с расчетного счета* в банковских выписках создавать и проводить **не нужно** — в 1С 8.3 кассовые операции с банком проводятся только кассовым ордером, иначе проводка \`Дт 50.01 Кт 51\` задвоится!\n` +
      `2. **Почему возникает «красное» (отрицательное) сальдо по счету \`50.01\`:**\n` +
      `   - Счет \`50.01\` — строго **активный** (нельзя выдать из кассы больше денег, чем там физически лежит). В вашей задаче начальный остаток по \`50.01\` составляет **${fmtRub(cashOpening)}**.\n` +
      `   - Если вы проводите выдачу зарплаты (РКО \`Дт 70 Кт 50.01\`) в один день со снятием наличных из банка (ПКО \`Дт 50.01 Кт 51\`), проверьте **время документов**: ПКО должен стоять раньше РКО (например, ПКО в \`10:00:00\`, а РКО в \`14:00:00\`).`
    );
  }

  // ---------------------------------------------------------------------------
  // 8. Штрафы, пени, неустойки, исполнительные листы (91.02 vs 99.02.3)
  // ---------------------------------------------------------------------------
  if (/(?:штраф|пен[яией]|неустойк|исполнительн|91\.02|99\.02)/i.test(q)) {
    return (
      `### Как разделить штрафы, неустойки и налоговые санкции в 1С 8.3:\n\n` +
      `В российском бухучете и 1С 8.3 действует строгое правило раздельного учета санкций:\n` +
      `- **Хозяйственные (договорные) штрафы, пени и неустойки контрагентам:**\n` +
      `  Начисляются в прочие расходы проводкой \`Дт 91.02 Кт 76.02\` (субконто *«Штрафы, пени и неустойки к получению (уплате)»*). Оплата: \`Дт 76.02 Кт 51\`.\n` +
      `- **Налоговые штрафы и санкции ИФНС (в бюджет):**\n` +
      `  Относить их на \`91.02\` **запрещено**, так как налоговые штрафы уплачиваются за счет чистой прибыли и никогда не уменьшают налог на прибыль (п. 2 ст. 270 НК РФ)! Они начисляются напрямую на счет прибылей и убытков: \`Дт 99.02.3 Кт 68.10\` (или соответствующий субсчет \`68\`). Оплата: \`Дт 68.10 Кт 51\`.\n\n` +
      `В 1С 8.3 начисление по исполнительному листу удобнее всего оформить документом **Операции → Операции, введенные вручную**, разбив сумму на две строки (\`91.02 / 76.02\` и \`99.02.3 / 68.10\`).`
    );
  }

  // ---------------------------------------------------------------------------
  // 9. Начальные остатки, счет 000 и пустые суммы
  // ---------------------------------------------------------------------------
  if (/(?:начальн.*остатк|счет\s+000|000|ввод\s+остатк|откуда\s+сумм|пуст.*сумм|требует\s+данн)/i.test(q)) {
    const totalDt = balances.reduce((s, b) => s + b.debit, 0);
    const totalKt = balances.reduce((s, b) => s + b.credit, 0);
    const diff = Math.round((totalDt - totalKt) * 100) / 100;

    return (
      `### Ввод начальных остатков и вспомогательный счет \`000\` в 1С 8.3:\n\n` +
      `1. В 1С:Бухгалтерия 8.3 остатки вводятся через **Главное → Помощник ввода остатков** датой **за 1 день до начала периода учета** (например, \`31.03.2026\` для учета с апреля 2026 г.).\n` +
      `2. Поскольку двойная запись требует двух счетов в каждой проводке, 1С использует технический счет \`000\`:\n` +
      `   - Активные остатки: \`Дт Активный счет Кт 000\`;\n` +
      `   - Пассивные остатки: \`Дт 000 Кт Пассивный счет\`.\n` +
      `3. Когда все активы и пассивы введены верно, обороты по Дт и Кт счета \`000\` равны, и **конечное сальдо счета \`000\` схлопывается в \`0,00 ₽\`**!\n\n` +
      `**Статус ваших остатков сейчас:** Итого Дт = **${fmtRub(totalDt)}**, Итого Кт = **${fmtRub(totalKt)}** (${
        Math.abs(diff) < 0.01
          ? 'баланс сходится идеально до копейки!'
          : `внимание: разница **${fmtRub(Math.abs(diff))}** — проверьте вкладку «Начальные остатки»!`
      }).\n` +
      `Именно из начальных остатков автоматически подтягиваются суммы для операций без явной цифры в условии (погашение прошлого НДС \`68.02\`, выплата зарплаты за прошлый месяц \`70\`, списание долга по конкретному договору на \`62.01\` / \`60.01\`).`
    );
  }

  // ---------------------------------------------------------------------------
  // 10. Универсальный контекстный ответ по открытой операции и ставке НДС
  // ---------------------------------------------------------------------------
  if (activeOp) {
    const postingsPreview = activeOp.postings
      .map((p) => `- \`Дт ${p.debitAccount} Кт ${p.creditAccount}\` — **${fmtRub(p.amount)}** (${p.comment})`)
      .join('\n');

    return (
      `Я вижу вашу текущую **Операцию №${activeOp.number} от ${activeOp.date}** (*«${activeOp.rawDescription}»*).\n\n` +
      `**Ключевая шпаргалка для ввода в 1С 8.3 (базовая ставка НДС организации — ${vatRate}%):**\n` +
      `- **Куда зайти в меню:** ${activeOp.menuPath1C.join(' → ')}\n` +
      `- **Документ и вид операции:** *${activeOp.documentType1C}* → *${activeOp.operationKind1C}*\n` +
      `- **Итоговая сумма:** **${fmtRub(activeOp.resolvedAmount)}**${activeOp.hasUpdOrSf ? ` (${activeOp.updLabel || 'включите тумблер УПД'})` : ''}\n\n` +
      `**Ожидаемые проводки в 1С (кнопка «ДтКт»):**\n${postingsPreview}\n\n` +
      `Вы можете уточнить у меня любой нюанс — например: *«Почему здесь выбран именно этот счет?»*, *«Как оформить УПД?»*, *«Почему не закрывается 20 счет?»* или *«Почему у меня расхождение в ОСВ?»*.`
    );
  }

  return (
    `Я ваш **Личный бухгалтер по 1С:Бухгалтерия 8.3 (ред. 3.0)**! Задайте любой вопрос по текущей задаче — например:\n` +
    `- *«Разбери проводки и НДС по текущей операции»*\n` +
    `- *«Почему здесь счет 20.01, а не 41?»*\n` +
    `- *«Как правильно оформить УПД в 1С 8.3?»*\n` +
    `- *«Не закрывается 20 счет при закрытии месяца, что проверить?»*\n` +
    `- *«Почему у меня расхождение в ОСВ?»*`
  );
}
